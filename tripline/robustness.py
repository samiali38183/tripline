def _text_transforms(command: str) -> list[tuple[str, str]]:
    """Whitespace and quoting spellings of a shell command string (first word kept intact)."""
    head, _, rest = command.partition(" ")
    tail = f" {rest}" if rest else ""
    transforms = [
        ("double-space", f"{head}  {rest}" if rest else command),
        ("tab", f"{head}\t{rest}" if rest else command),
        ("leading-space", f" {command}"),
        ("trailing-semicolon", f"{command};"),
        ("quoted-command", f'"{head}"{tail}'),
        ("single-quoted-command", f"'{head}'{tail}"),
        ("split-quote", f"{head[0]}''{head[1:]}{tail}" if len(head) > 1 else command),
        ("backslash", f"\\{head}{tail}"),
        ("command-prefix", f"command {command}"),
        ("env-prefix", f"FOO=1 {command}"),
        ("subshell", f"({command})"),
        ("brace-group", f"{{ {command}; }}"),
        ("eval", f'eval "{command}"'),
    ]
    return transforms


