"""Evasion sweep: how many spellings of the same attack do the rules still catch?

A scenario pass says the rule fires on one recording of one command. This module generates
deterministic variants of that command that stay the same attack (other binary paths, flag
clustering, argument order, operand path forms, wrapper prefixes, mode spellings, whitespace and
quoting inside shell wrappers, ...) and replays each through the rules.

How variants are built
    * A *template* event is taken from the scenario's committed fixture (the first ``EXECVE`` or
      the first file event). Every synthetic event copies the template's shape (uid, cwd, key,
      ...) and overrides only ``exe``, ``a0..aN``, ``argc``, ``proctitle`` and, for file events,
      ``TargetFilename``/``paths``.
    * A variant is a *set* of events, because one shell command line often produces several
      execve records (``bash -c "rm f"`` then ``rm f``). A rule catches a variant when it matches
      at least one of them. Shell quoting and whitespace are resolved by the shell before the
      child's execve, so they only matter for the wrapper event and for shell builtins
      (``history -c``), which exist as a wrapper command line only.
    * Families whose ``kind`` is ``cmdline`` keep the same tool; ``alt-tool`` families reach the
      same effect with another tool (for example ``install -m 4755``) and are reported apart.
    * Variants that were generated by random combination use :data:`SEED`; the rest are fixed
      lists. The sweep is deterministic: the same code gives the same table.

Limits (also in ``docs/robustness.md``): the lists are hand-written from known shell and
coreutils behaviour, not exhaustive; variants are evaluated at the event level, not by running
them; the child event of a wrapper is assumed to be recorded (auditd records every execve).
A high catch rate here is not a proof of robustness, and a low one is a documented gap.
"""

from __future__ import annotations

import copy
import itertools
import random
import re
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from tripline.engine.rules import RuleSet, evaluate
from tripline.models import (
    Event,
    RobustnessReport,
    RobustnessRule,
    RobustnessScenario,
    RobustnessVariant,
    Scenario,
)
from tripline.replay import load_fixture_events

SEED = 20261111
"""Seed for the randomly combined families."""
COMBINED_SAMPLES = 40

KIND_CMDLINE = "cmdline"
KIND_ALT_TOOL = "alt-tool"

_ARG = re.compile(r"a\d+")
_SHELL = "/usr/bin/bash"


@dataclass(frozen=True, slots=True)
class Variant:
    """A generated attack spelling: the events it would produce plus its description."""

    family: str
    label: str
    events: tuple[Event, ...]
    kind: str = KIND_CMDLINE


@dataclass(slots=True)
class Templates:
    """Template events lifted from a scenario's fixture."""

    execve: Event
    file: Event | None = None


def exec_event(template: Event, argv: list[str], exe: str) -> Event:
    """Copy ``template`` and replace the process fields (``exe``, ``a0..aN``, ``proctitle``)."""
    event = {
        k: copy.deepcopy(v)
        for k, v in template.items()
        if not _ARG.fullmatch(k)
        and k not in {"argc", "proctitle", "exe", "comm", "CommandLine", "Image", "paths"}
    }
    event.update({f"a{i}": a for i, a in enumerate(argv)})
    event.update(
        {
            "argc": str(len(argv)),
            "exe": exe,
            "comm": exe.rsplit("/", 1)[-1][:15],
            "proctitle": " ".join(argv),
            "type": "EXECVE",
            "paths": [{"name": exe, "nametype": "NORMAL", "mode": "0100755"}],
        }
    )
    return event


def file_event(template: Event, path: str) -> Event:
    """Copy a file-creation ``template`` and point it at ``path``."""
    event = copy.deepcopy(template)
    event["TargetFilename"] = path
    directory = path.rsplit("/", 1)[0] + "/"
    event["paths"] = [
        {"name": directory, "nametype": "PARENT", "mode": "040755"},
        {"name": path, "nametype": "CREATE", "mode": "0100644"},
    ]
    return event


def _wrapper(t: Templates, text: str) -> Event:
    return exec_event(t.execve, ["bash", "-c", text], _SHELL)


# --------------------------------------------------------------------------- T1548.001 setuid

SETUID_SYMBOLIC = [
    "u+s", "u+xs", "g+s", "g+xs", "ug+s", "a+s", "+s", "u=rwxs", "u+rwxs",
    "g+w,u+s", "u+s,g+w", "a=rwxs", "u+x,u+s", "u+s,go-w",
]  # fmt: skip
SETUID_OCTAL = ["4755", "04755", "2755", "6755", "7755", "4777", "4000", "06755", "4111"]
CHMOD_ARGV0 = ["chmod", "/bin/chmod", "/usr/bin/chmod", "/usr/local/bin/../../bin/chmod"]
CHMOD_FLAGS: list[list[str]] = [
    [], ["-v"], ["-R"], ["-f"], ["-vR"], ["-Rf"], ["-c"], ["--verbose"], ["--recursive"],
    ["--"], ["-v", "--"], ["--quiet", "--"],
]  # fmt: skip
OPERANDS = [
    "/tmp/evilBinary", "./evilBinary", "/tmp//evilBinary", "/tmp/../tmp/evilBinary",
    "/home/runner/evil binary", "/dev/shm/x", "evilBinary",
]  # fmt: skip


def _chmod(t: Templates, argv0: str, args: list[str], exe: str = "/usr/bin/chmod") -> Event:
    return exec_event(t.execve, [argv0, *args], exe)


def setuid_variants(t: Templates) -> list[Variant]:
    """Spellings of ``chmod u+xs /tmp/evilBinary`` (Atomic Red Team T1548.001)."""
    out: list[Variant] = []
    base = "/tmp/evilBinary"
    for mode in SETUID_SYMBOLIC + SETUID_OCTAL:
        out.append(
            Variant("mode-form", f"chmod {mode} {base}", (_chmod(t, "chmod", [mode, base]),))
        )
    for argv0, exe in itertools.product(CHMOD_ARGV0, ["/usr/bin/chmod", "/bin/chmod"]):
        out.append(
            Variant(
                "binary-path",
                f"{argv0} u+xs {base} (exe {exe})",
                (_chmod(t, argv0, ["u+xs", base], exe),),
            )
        )
    for flags in CHMOD_FLAGS:
        out.append(
            Variant(
                "flags-before-mode",
                f"chmod {' '.join(flags)} 4755 {base}".replace("  ", " "),
                (_chmod(t, "chmod", [*flags, "4755", base]),),
            )
        )
    for args in (
        ["u+s", "-v", base],
        ["u+s", "--", base],
        ["u+s", base, "-R"],
        ["-R", "u+s", base, "-v"],
        ["u+s", base, "/tmp/second"],
        ["u+s", "/tmp/first", base],
        ["--", "4755", base],
    ):
        out.append(
            Variant("argument-order", "chmod " + " ".join(args), (_chmod(t, "chmod", args),))
        )
    for operand in OPERANDS:
        out.append(
            Variant("operand-path", f"chmod u+s {operand}", (_chmod(t, "chmod", ["u+s", operand]),))
        )
    for operand in (
        "/usr/share/doc/evil/bin",
        "/usr/share/doc/../../../tmp/evilBinary",
    ):
        out.append(
            Variant("operand-path", f"chmod u+s {operand}", (_chmod(t, "chmod", ["u+s", operand]),))
        )
    out.append(
        Variant(
            "operand-path",
            f"chmod u+s {base} /usr/share/doc/x",
            (_chmod(t, "chmod", ["u+s", base, "/usr/share/doc/x"]),),
        )
    )
    for prefix in (
        ["sudo"],
        ["sudo", "-n"],
        ["env", "FOO=1"],
        ["nice", "-n", "5"],
        ["timeout", "5"],
        ["stdbuf", "-o0"],
    ):
        exe = "/usr/bin/" + prefix[0]
        out.append(
            Variant(
                "wrapper-prefix",
                " ".join([*prefix, "chmod", "u+xs", base]),
                (
                    exec_event(t.execve, [*prefix, "chmod", "u+xs", base], exe),
                    _chmod(t, "chmod", ["u+xs", base]),
                ),
            )
        )
    out.append(
        Variant(
            "renamed-binary",
            "cp /bin/chmod /tmp/.c; /tmp/.c u+s f",
            (exec_event(t.execve, ["/tmp/.c", "u+s", base], "/tmp/.c"),),
        )
    )
    out.append(
        Variant(
            "multicall-binary",
            "busybox chmod u+s f",
            (exec_event(t.execve, ["busybox", "chmod", "u+s", base], "/usr/bin/busybox"),),
        )
    )
    rng = random.Random(SEED)
    axes = (CHMOD_ARGV0, CHMOD_FLAGS, SETUID_SYMBOLIC + SETUID_OCTAL, OPERANDS)
    seen: set[tuple[str, ...]] = set()
    while len(seen) < COMBINED_SAMPLES:
        argv0 = rng.choice(axes[0])
        flags = rng.choice(axes[1])
        mode = rng.choice(axes[2])
        operand = rng.choice(axes[3])
        key = (argv0, *flags, mode, operand)
        if key in seen:
            continue
        seen.add(key)
        argv = [argv0, *flags, mode, operand]
        out.append(
            Variant(
                "random-combination", " ".join(argv), (_chmod(t, argv0, [*flags, mode, operand]),)
            )
        )
    for label, argv, exe in (
        (
            "install -m 4755 /tmp/src /tmp/dst",
            ["install", "-m", "4755", "/tmp/src", "/tmp/dst"],
            "/usr/bin/install",
        ),
        (
            "install -m4755 /tmp/src /tmp/dst",
            ["install", "-m4755", "/tmp/src", "/tmp/dst"],
            "/usr/bin/install",
        ),
        (
            "python3 -c os.chmod(f, 0o4755)",
            ["python3", "-c", "import os; os.chmod('/tmp/f', 0o4755)"],
            "/usr/bin/python3",
        ),
        ("perl -e chmod 04755, f", ["perl", "-e", "chmod 04755, '/tmp/f'"], "/usr/bin/perl"),
    ):
        out.append(
            Variant("alternative-tool", label, (exec_event(t.execve, argv, exe),), KIND_ALT_TOOL)
        )
    return out


