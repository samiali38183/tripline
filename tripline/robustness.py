"""Scenario id -> variant generator."""

COMPARISON_RULES: dict[str, tuple[str, ...]] = {
    "t1548-001-setuid-setgid": ("c21c4eaa-ba2e-419a-92b2-8371703cbe21",),
}
"""Extra rules swept next to the scenario's expected rules (the vendored upstream setuid rule)."""


@dataclass(slots=True)
class _Tally:
    rule_id: str
    title: str
    expected: bool
    counts: dict[str, list[int]] = field(
        default_factory=lambda: {KIND_CMDLINE: [0, 0], KIND_ALT_TOOL: [0, 0]}
    )


def sweep_scenario(
    scenario_id: str,
    technique: str,
    expected_rules: list[str],
    templates: Templates,
    rules: RuleSet,
) -> RobustnessScenario:
    """Generate the scenario's variants and replay each through its rules."""
    variants = GENERATORS[scenario_id](templates)
    rule_ids = list(dict.fromkeys([*expected_rules, *COMPARISON_RULES.get(scenario_id, ())]))
    tallies: dict[str, _Tally] = {}
    for rule_id in rule_ids:
        compiled = rules.by_id(rule_id)
        tallies[rule_id] = _Tally(
            rule_id, compiled.title if compiled else "<rule not loaded>", rule_id in expected_rules
        )
    results: list[RobustnessVariant] = []
    for variant in variants:
        caught: dict[str, bool | None] = {}
        for rule_id in rule_ids:
            compiled = rules.by_id(rule_id)
            verdicts = (
                [evaluate(compiled, e) for e in variant.events] if compiled is not None else []
            )
            if compiled is not None and all(v is None for v in verdicts):
                caught[rule_id] = None
                continue
            hit = any(v is True for v in verdicts)
            caught[rule_id] = hit
            counts = tallies[rule_id].counts[variant.kind]
            counts[0] += 1
            counts[1] += int(hit)
        results.append(
            RobustnessVariant(
                family=variant.family, kind=variant.kind, label=variant.label, caught=caught
            )
        )
    totals = {KIND_CMDLINE: [0, 0], KIND_ALT_TOOL: [0, 0]}
    for variant_result in results:
        cell = totals[variant_result.kind]
        cell[0] += 1
        cell[1] += int(any(variant_result.caught.get(r) is True for r in expected_rules))
    return RobustnessScenario(
        scenario_id=scenario_id,
        technique=technique,
        variants=results,
        cmdline_total=totals[KIND_CMDLINE][0],
        cmdline_any_caught=totals[KIND_CMDLINE][1],
        alt_tool_total=totals[KIND_ALT_TOOL][0],
        alt_tool_any_caught=totals[KIND_ALT_TOOL][1],
        rules=[
            RobustnessRule(
                rule_id=t.rule_id,
                title=t.title,
                expected=t.expected,
                cmdline_variants=t.counts[KIND_CMDLINE][0],
                cmdline_caught=t.counts[KIND_CMDLINE][1],
                alt_tool_variants=t.counts[KIND_ALT_TOOL][0],
                alt_tool_caught=t.counts[KIND_ALT_TOOL][1],
            )
            for t in tallies.values()
        ],
    )


def templates_from(events: list[Event]) -> Templates | None:
    """Pick the template events out of a fixture; ``None`` when it has no ``EXECVE`` event."""
    execve = next((e for e in events if e.get("type") == "EXECVE" and "SYSCALL" in e), None)
    if execve is None:
        return None
    file = next((e for e in events if "TargetFilename" in e), None)
    return Templates(execve=execve, file=file)


def family_table(
    scenario: RobustnessScenario, expected: list[str] | None = None
) -> dict[str, dict[str, tuple[int, int]]]:
    """``family -> rule_id -> (caught, applicable)`` in generation order.

    The key ``"any"`` holds the family's variants caught by at least one expected rule (all rules
    when ``expected`` is ``None``) out of all of the family's variants.
    """
    table: dict[str, dict[str, list[int]]] = {}
    for v in scenario.variants:
        row = table.setdefault(v.family, {})
        for rule_id, hit in v.caught.items():
            if hit is None:
                continue
            cell = row.setdefault(rule_id, [0, 0])
            cell[0] += int(hit)
            cell[1] += 1
        pool = expected if expected is not None else list(v.caught)
        cell = row.setdefault("any", [0, 0])
        cell[0] += int(any(v.caught.get(r) is True for r in pool))
        cell[1] += 1
    return {f: {r: (c[0], c[1]) for r, c in row.items()} for f, row in table.items()}


def run_sweep(scenarios: list[Scenario], rules: RuleSet, root: Path) -> RobustnessReport:
    """Sweep every scenario that has a generator and a fixture to take templates from."""
    swept: list[RobustnessScenario] = []
    for scenario in sorted(scenarios, key=lambda s: s.id):
        if scenario.id not in GENERATORS or not scenario.fixtures:
            continue
        templates = templates_from(load_fixture_events(scenario, root))
        if templates is None:
            continue
        swept.append(
            sweep_scenario(
                scenario.id, scenario.technique, list(scenario.expected_rules), templates, rules
            )
        )
    return RobustnessReport(seed=SEED, scenarios=swept)
